async function run() {
  console.log('--- 1. Updating 43 existing YAML files with Gout data ---');

  const files = fs.readdirSync(DATA_DIR, { recursive: true }) as string[];
  let updatedCount = 0;

  for (const file of files) {
    if (!file.endsWith('.yaml')) continue;
    const fullPath = path.join(DATA_DIR, file);
    const raw = fs.readFileSync(fullPath, 'utf-8');
    const doc = load(raw) as any;

    if (!doc || !doc.id) continue;

    const goutProfile = GOUT_DATA[doc.id];
    if (goutProfile) {
      if (!doc.diseases) doc.diseases = {};
      doc.diseases.gout = goutProfile;

      // Add gout reference sources if not already in doc sources
      if (!doc.sources) doc.sources = [];
      const hasGoutSource = doc.sources.some((s: any) => s.name.includes('สมาคมรูมาติสซั่ม'));
      if (!hasGoutSource) {
        doc.sources.push({
          name: 'สมาคมรูมาติสซั่มแห่งประเทศไทย',
          url: 'https://thairheumatology.org/',
        });
      }

      fs.writeFileSync(fullPath, dump(doc, { lineWidth: -1, noRefs: true }), 'utf-8');
      updatedCount++;
      console.log(`✓ Updated [${doc.id}] at ${file}`);
    } else {
      console.warn(`! No gout profile mapped for: ${doc.id}`);
    }
  }

  console.log(`\nUpdated ${updatedCount} existing files successfully.`);

  console.log('\n--- 2. Creating 8 new landmark Gout food files ---');
  for (const item of NEW_FOODS) {
    const targetFolder = path.join(DATA_DIR, item.category);
    if (!fs.existsSync(targetFolder)) {
      fs.mkdirSync(targetFolder, { recursive: true });
    }
    const targetFile = path.join(targetFolder, `${item.id}.yaml`);
    fs.writeFileSync(targetFile, dump(item, { lineWidth: -1, noRefs: true }), 'utf-8');
    console.log(`+ Created landmark food: ${item.name} at ${targetFile}`);
  }

  console.log('\n=== All Gout data migration completed successfully! ===');
}

run().catch((err) => {
  console.error('Error running update-gout-data:', err);
  process.exit(1);
});
